#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd)"

usage() {
  cat <<'EOF'
WM Bench AutoDL deployment helper

Usage:
  bash infra/autodl/deploy.sh [command]

Commands:
  up        Prepare environment, build web UI, start API + worker, print tunnel info. Default.
  restart   Stop existing service sessions, then run up.
  stop      Stop API + worker screen sessions.
  status    Show service sessions and health check result.
  logs      Print log file locations and recent lines.
  tunnel    Print AutoDL/SSH tunnel instructions for the configured port.
  help      Show this help.

Useful environment variables:
  API_PORT=6006
  WM_BENCH_DEVICE=cuda:0
  WM_BENCH_INSTALL_SHARP_DEPS=0
  WM_BENCH_AUTO_INSTALL_NODE=0
  WM_BENCH_AUTO_INSTALL_SCREEN=0
EOF
}

load_profile() {
  # shellcheck disable=SC1091
  source "${SCRIPT_DIR}/common.sh"
  autodl_load_env
  autodl_prepare_dirs
}

check_linux() {
  if [[ "$(uname -s)" != "Linux" ]]; then
    echo "This deploy helper targets AutoDL/Linux. Current OS: $(uname -s)" >&2
    echo "For local development use scripts/start-macos.sh or scripts/start-windows.ps1." >&2
    exit 1
  fi
}

local_api_host() {
  autodl_local_host "${API_HOST}"
}

health_url() {
  echo "http://$(local_api_host):${API_PORT}/health"
}

public_url_hint() {
  local public
  public="$(autodl_public_url_for_port "${API_PORT}")"
  if [[ -n "${public}" ]]; then
    echo "${public}"
  else
    echo "http://$(local_api_host):${API_PORT}"
  fi
}

print_tunnel_info() {
  load_profile
  local host health public public_health
  host="$(local_api_host)"
  health="http://${host}:${API_PORT}/health"
  public="$(autodl_public_url_for_port "${API_PORT}")"

  cat <<EOF
Tunnel / public access

The production AutoDL profile serves the built Web UI and API on one port:
  Server-local URL: http://${host}:${API_PORT}
  Health check:     ${health}
EOF

  if [[ -n "${public}" ]]; then
    public_health="${public%/}/health"
    cat <<EOF
  Public URL:       ${public}
  Public health:    ${public_health}

The public URL above is provided by AutoDL for local port ${API_PORT}.
EOF
  else
    cat <<EOF

Recommended AutoDL console path:
  1. Open the AutoDL instance page.
  2. Add a custom service / tunnel for local port ${API_PORT}.
  3. Open the public URL generated by AutoDL.
EOF
  fi

  cat <<EOF

SSH tunnel alternative from your own computer:
  ssh -L ${API_PORT}:127.0.0.1:${API_PORT} root@<server-ip>
  open http://127.0.0.1:${API_PORT}

Security note:
  WM Bench currently has no login/auth layer. Prefer AutoDL's controlled tunnel,
  SSH forwarding, VPN, or a reverse proxy with access control. Do not expose it
  directly to untrusted public users.
EOF
}

show_status() {
  load_profile
  local health public public_health
  health="$(health_url)"
  public="$(autodl_public_url_for_port "${API_PORT}")"

  echo "Screen sessions:"
  if command -v screen >/dev/null 2>&1; then
    screen -ls | grep wmbench || echo "  none"
  else
    echo "  screen is not installed"
  fi

  echo
  echo "Health:"
  if command -v curl >/dev/null 2>&1 && curl -fsS "${health}" >/dev/null 2>&1; then
    echo "  ok: ${health}"
  else
    echo "  not reachable yet: ${health}"
  fi

  echo
  echo "Public access:"
  if [[ -n "${public}" ]]; then
    public_health="${public%/}/health"
    echo "  url: ${public}"
    if command -v curl >/dev/null 2>&1 && curl -fsSk --connect-timeout 5 --max-time 10 "${public_health}" >/dev/null 2>&1; then
      echo "  ok:  ${public_health}"
    else
      echo "  not reachable yet: ${public_health}"
    fi
  else
    echo "  no AutoDL public URL detected for local port ${API_PORT}"
    autodl_list_public_service_urls || true
  fi

  echo
  echo "Paths:"
  echo "  resources: ${WM_BENCH_RESOURCES_ROOT}"
  echo "  runs:      ${WM_BENCH_RUNS_ROOT}"
  echo "  state:     ${WM_BENCH_RUNS_ROOT}/_experiment_state"
  echo "  logs:      ${WM_BENCH_LOG_DIR}"
}

show_logs() {
  load_profile

  echo "Log files:"
  echo "  API:    ${WM_BENCH_LOG_DIR}/api.screen.log"
  echo "  Worker: ${WM_BENCH_LOG_DIR}/worker.screen.log"
  echo

  for log_file in "${WM_BENCH_LOG_DIR}/api.screen.log" "${WM_BENCH_LOG_DIR}/worker.screen.log"; do
    echo "==> ${log_file}"
    if [[ -f "${log_file}" ]]; then
      tail -n 80 "${log_file}"
    else
      echo "not found"
    fi
    echo
  done
}

run_up() {
  check_linux
  bash "${SCRIPT_DIR}/start.sh"
  echo
  print_tunnel_info
}

case "${1:-up}" in
  up)
    run_up
    ;;
  restart)
    check_linux
    bash "${SCRIPT_DIR}/stop.sh"
    run_up
    ;;
  stop)
    bash "${SCRIPT_DIR}/stop.sh"
    ;;
  status)
    show_status
    ;;
  logs)
    show_logs
    ;;
  tunnel)
    print_tunnel_info
    ;;
  help|--help|-h)
    usage
    ;;
  *)
    echo "Unknown command: $1" >&2
    echo >&2
    usage >&2
    exit 2
    ;;
esac
